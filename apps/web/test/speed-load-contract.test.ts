import { readFileSync } from "node:fs";
import { afterEach, beforeEach, expect, it, vi } from "vitest";
import { GET } from "../app/api/athlete/models/speed-load/route";
import { currentAuthorizedAthlete } from "../lib/account-access";
import { parseSpeedLoad, type SpeedLoad } from "../lib/speed-load";
import { readSpeedLoad } from "../lib/speed-load-client";

vi.mock("../lib/account-access", () => ({ currentAuthorizedAthlete: vi.fn() }));
vi.mock("../lib/api-readiness", () => ({ waitForApi: vi.fn() }));

// Keep the server/browser contract tied to the actual producing backend. A new
// calculation version must not turn its successful HTTP 200 into a Next 503.
const backendSource = readFileSync(new URL("../../api/speed_load.py", import.meta.url), "utf8");
const backendVersion = backendSource.match(/^VERSION\s*=\s*"([^"]+)"/m)![1];
// Generated by apps.api.speed_load.history_view with the synthetic raw_stream
// and raw_profile fixtures, one recorded Run minute on 2026-10-28. Includes the
// complete current comparison/profile payload rather than a hand-written shape.
const report = JSON.parse(readFileSync(new URL("./fixtures/speed-load-current.json", import.meta.url), "utf8")) as SpeedLoad;

beforeEach(() => {
  vi.stubEnv("ONFLOWS_API_BASE_URL", "https://api.test");
  vi.stubEnv("ONFLOWS_SERVICE_TOKEN", "test-token");
  vi.mocked(currentAuthorizedAthlete).mockResolvedValue({ userId: "user", actorUserId: "user", athleteAlias: "selected",
    displayName: "Example", isOwner: true, canEditPlan: true, canViewRecovery: true });
});
afterEach(() => { vi.unstubAllGlobals(); vi.unstubAllEnvs(); vi.resetAllMocks(); });

it("forwards the current backend report through the real API parser and the authorized Next route", async () => {
  expect(report.model_version).toBe(backendVersion);
  const fetcher = vi.fn().mockResolvedValue(Response.json(report));
  vi.stubGlobal("fetch", fetcher);
  const response = await GET(new Request("https://app.test/api/athlete/models/speed-load"));
  expect(response.status).toBe(200);
  expect(await response.json()).toEqual(report);
  expect(fetcher).toHaveBeenCalledTimes(1);
});

it("accepts current reports in the browser while retaining raw-speed provenance", async () => {
  vi.stubGlobal("fetch", vi.fn().mockResolvedValue(Response.json(report)));
  const result = await readSpeedLoad({ generation: "g", revision: 1 });
  expect(result.model_version).toBe(backendVersion);
  expect(result.activities[0]).toMatchObject({ speed_role: "RAW_MOVING_SPEED", initial_heuristic: true });
});

it("retains retrospective reports and still rejects unknown versions or inconsistent accounting", () => {
  expect(parseSpeedLoad({ ...report, model_version: "speed-load-common-profile-v6-retrospective-tests" }).model_version)
    .toBe("speed-load-common-profile-v6-retrospective-tests");
  expect(() => parseSpeedLoad({ ...report, model_version: "unknown-load-model" })).toThrow();
  expect(() => parseSpeedLoad({ ...report, accounted_minutes: report.accounted_minutes! + 1 })).toThrow();
});
